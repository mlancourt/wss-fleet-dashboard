#!/usr/bin/env node
/**
 * make-quote-logo.js — D83. Bakes worker/assets/wss-logo.jpeg (the brand mark,
 * copied from the vault's Catalog/Assets/brand/wss-logo-356.jpeg — never
 * upscale it) into worker/quote-logo.js as base64, so the Worker can embed it
 * in the quote PDF without a binary-module rule in wrangler.toml.
 *
 *   node tools/make-quote-logo.js
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'worker/assets/wss-logo.jpeg');
const bytes = fs.readFileSync(src);
if (bytes.length > 40 * 1024) throw new Error(`logo is ${bytes.length} bytes — spec caps it at 40 KB`);
const out = `// GENERATED by tools/make-quote-logo.js from worker/assets/wss-logo.jpeg — do not hand-edit.\n`
  + `// The WSS mark for the quote PDF header (${bytes.length} bytes, JPEG).\n`
  + `export const LOGO_JPEG_B64 = '${bytes.toString('base64')}';\n`;
fs.writeFileSync(path.join(root, 'worker/quote-logo.js'), out);
console.log(`worker/quote-logo.js: ${bytes.length} bytes`);
